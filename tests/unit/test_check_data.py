def test_check_data_unrecognized_dir(tmp_path):
    """Directories that don't match any registry module are reported as unrecognized."""
    registry_dir = tmp_path / "registry"
    registry_dir.mkdir()
    # registry = fake_registry({"fair-temperature": {"module_name": "fair-temperature"}})
    registry_fs = FileSystemModuleRegistry(registry_dir)

    module_specific = tmp_path / "module_specific_input_data"
    (module_specific / "unknown-module").mkdir(parents=True)

    result = check_data(
        module_specific_input_dir=module_specific,
        shared_input_dir=tmp_path / "shared",
        definitions=registry_fs,
    )

    assert result.unrecognized_dirs == ["unknown-module"]
    assert result.module_results == []


def test_check_data_empty_dir(tmp_path):
    """An empty module_specific_input_data dir returns an empty result."""

    module_specific_input_dir = Path(tmp_path, "module_specific_inputs")
    module_specific_input_dir.mkdir()
    shared_input_dir = Path(tmp_path, "shared_input")
    shared_input_dir.mkdir()

    registry_path = Path(tmp_path, "fake_registry")
    registry_path.mkdir()
    fake_registry_fs = FileSystemModuleRegistry(registry_path)

    result = check_data(
        module_specific_input_dir=module_specific_input_dir,
        shared_input_dir=shared_input_dir,
        definitions=fake_registry_fs,
    )

    assert result.module_results == []
    assert result.unrecognized_dirs == []


def test_check_data_missing_dir(tmp_path, fake_registry):
    """A non-existent module_specific_input_data dir returns an empty result without error."""
    # registry = ModuleRegistry(tmp_path / "registry")
