def test_check_module_result_counts_present_missing_skipped():
    result = CheckModuleResult(
        module_name="test-module",
        checks=[
            InputFileCheck(field_name="a", expected_path=Path("a.nc"), exists=True),
            InputFileCheck(field_name="b", expected_path=Path("b.nc"), exists=False),
            InputFileCheck(field_name="c", expected_path=Path("c.csv"), exists=True),
            InputFileCheck(
                field_name="d",
                expected_path=Path(),
                exists=False,
                skipped=True,
                skip_reason="inter-module dep.",
            ),
        ],
    )
    assert result.n_present == 2
    assert result.n_missing == 1
    assert result.n_checkable == 3


